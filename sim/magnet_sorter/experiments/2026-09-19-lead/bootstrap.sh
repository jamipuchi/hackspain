#!/usr/bin/env bash
# Root-free MuJoCo headless bootstrap for the magnet sorter.
#
# Recreates the whole render environment from scratch in a fresh worker container:
#   * an OSMesa + libGL stack unpacked from Ubuntu noble .debs into a user-writable prefix
#   * a Python 3.12 venv at contracts/.venv with the pinned requirements
#
# Idempotent: re-running skips work that is already in place. Safe to run concurrently-ish.
# Requires no root, no sudo, no /dev/dri, no display.
#
# Usage:
#   bash sim/magnet_sorter/experiments/2026-09-19-lead/bootstrap.sh
#   source sim/magnet_sorter/experiments/2026-09-19-lead/env.sh   # then export the vars it prints
#
# Override the install location with SORTER_TOOLCHAIN_PREFIX.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"

# /workspace/shared itself is root-owned; /workspace/shared/misc/<agent-id>/ is worker-owned.
# Every agent runs as uid 1001 (worker), so any worker-owned dir under /workspace/shared is a
# genuinely shared prefix. Pick the first writable candidate.
default_prefix() {
  if [ -n "${SORTER_TOOLCHAIN_PREFIX:-}" ]; then
    printf '%s' "$SORTER_TOOLCHAIN_PREFIX"; return
  fi
  local c
  for c in /workspace/shared/misc/*/; do
    if [ -w "$c" ]; then printf '%s' "${c}toolchains"; return; fi
  done
  printf '%s' "${HOME}/toolchains"
}

PREFIX="$(default_prefix)"
GL_ROOT="$PREFIX/osmesa"
GL_LIB="$GL_ROOT/usr/lib/x86_64-linux-gnu"
APT_DIR="$PREFIX/apt"
VENV="$REPO_ROOT/contracts/.venv"

echo "==> repo   : $REPO_ROOT"
echo "==> prefix : $PREFIX"

# ---------------------------------------------------------------- GL libraries
# libosmesa6 pulls in the llvmpipe software rasteriser, so this works with no GPU
# and no /dev/dri. The libgl1/libglx0 group is only needed because OpenCV dlopens
# libGL.so.1 at import time; MuJoCo's osmesa backend does not use it.
PACKAGES=(
  libosmesa6 libglapi-mesa libllvm17t64
  libdrm2 libdrm-amdgpu1 libdrm-nouveau2 libdrm-radeon1 libdrm-intel1
  libpciaccess0 libelf1t64 libzstd1 libsensors5 libedit2 libffi8
  libgl1 libglx0 libglvnd0 libglx-mesa0 libegl1
  libx11-6 libxau6 libxdmcp6 libxcb1 libxext6 libxfixes3 libxxf86vm1
  libxshmfence1 libbsd0 libmd0 libwayland-client0 libwayland-server0
  libxcb-dri3-0 libxcb-present0 libxcb-sync1 libxcb-xfixes0 libxcb-randr0
  libxcb-glx0 libxcb-shm0 libxcb-dri2-0
)

if [ -f "$GL_LIB/libOSMesa.so.8" ] && [ -f "$GL_LIB/libGL.so.1" ]; then
  echo "==> GL stack already present, skipping download"
else
  echo "==> provisioning GL stack into $GL_ROOT"
  mkdir -p "$APT_DIR/lists/partial" "$APT_DIR/cache/archives/partial" "$APT_DIR/debs" "$GL_ROOT"

  # apt-get needs writable state dirs; redirect all of them into the prefix so no
  # root-owned path under /var is touched.
  cat > "$APT_DIR/apt.conf" <<EOF
Dir::State::lists "$APT_DIR/lists";
Dir::Cache "$APT_DIR/cache";
Dir::Cache::archives "$APT_DIR/cache/archives";
Dir::State::status "/var/lib/dpkg/status";
EOF

  # The image ships with empty apt lists, so `download` cannot resolve versions
  # until we populate them. This writes only into $APT_DIR.
  APT_CONFIG="$APT_DIR/apt.conf" apt-get update >/dev/null 2>&1 || true

  ( cd "$APT_DIR/debs" && APT_CONFIG="$APT_DIR/apt.conf" apt-get download "${PACKAGES[@]}" >/dev/null )

  # dpkg-deb -x unpacks without touching the dpkg database, so no root needed.
  for deb in "$APT_DIR"/debs/*.deb; do dpkg-deb -x "$deb" "$GL_ROOT"; done
  echo "==> unpacked $(ls "$APT_DIR"/debs/*.deb | wc -l) packages"
fi

if ! LD_LIBRARY_PATH="$GL_LIB" ldd "$GL_LIB/libOSMesa.so.8" 2>&1 | grep -q "not found"; then
  echo "==> libOSMesa.so.8 dependencies all resolve"
else
  echo "!! libOSMesa.so.8 has unresolved dependencies:" >&2
  LD_LIBRARY_PATH="$GL_LIB" ldd "$GL_LIB/libOSMesa.so.8" | grep "not found" >&2
  exit 1
fi

# ---------------------------------------------------------------------- Python
# Host python3 is 3.12.3 and is sufficient. Do NOT build CPython 3.14 from source:
# this image lacks the OpenSSL and libffi headers, so such a build yields an
# interpreter with no _ssl and no _ctypes.
if [ -x "$VENV/bin/python" ]; then
  echo "==> venv already present at $VENV"
else
  echo "==> creating venv at $VENV"
  python3 -m venv "$VENV"
fi

echo "==> installing requirements"
"$VENV/bin/python" -m pip install -q --upgrade pip >/dev/null
"$VENV/bin/python" -m pip install -q \
  -r "$REPO_ROOT/contracts/learning/requirements.txt" openai==3.16.2

# ------------------------------------------------------------------ env script
cat > "$(dirname "${BASH_SOURCE[0]}")/env.sh" <<EOF
# Generated by bootstrap.sh. Source this before running any renderer or test.
export LD_LIBRARY_PATH="$GL_LIB\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export MUJOCO_GL=osmesa
export PYOPENGL_PLATFORM=osmesa
export PYTHONDONTWRITEBYTECODE=1
EOF
echo "==> wrote env.sh"

# ----------------------------------------------------------------- self-verify
export LD_LIBRARY_PATH="$GL_LIB${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export MUJOCO_GL=osmesa PYOPENGL_PLATFORM=osmesa PYTHONDONTWRITEBYTECODE=1

echo "==> verifying offscreen render of the magnet_sorter scene"
( cd "$REPO_ROOT/sim/magnet_sorter" && "$VENV/bin/python" - <<'PY'
import sys
import mujoco, scene_def as sd, mujoco_model

model, data, _ = mujoco_model.load()
mujoco.mj_forward(model, data)

height = max(c["height"] for c in sd.CAMERAS.values())
width = max(c["width"] for c in sd.CAMERAS.values())

# One Renderer shared across every camera. Constructing a second mujoco.Renderer
# creates a second OSMesa context, and the older context then renders
# uninitialised framebuffer noise (mean ~2, visually black with colour speckle).
renderer = mujoco.Renderer(model, height=height, width=width)

failed = False
for name in sd.CAMERAS:
    renderer.update_scene(data, camera=f"cam_{name}")
    img = renderer.render()
    blank = img.std() < 25.0
    print(f"cam_{name}: shape={img.shape} mean={img.mean():.3f} std={img.std():.3f} "
          f"{'BLANK/FAIL' if blank else 'ok'}")
    failed |= blank

sys.exit(1 if failed else 0)
PY
)

echo "==> running the focused suite under both build configs"
( cd "$REPO_ROOT" && "$VENV/bin/python" -m unittest \
    sim/magnet_sorter/test_agent_brain.py sim/magnet_sorter/test_camera.py 2>&1 | tail -3 )
( cd "$REPO_ROOT" && SORTER_BUILD=theker_v1 "$VENV/bin/python" -m unittest \
    sim/magnet_sorter/test_agent_brain.py sim/magnet_sorter/test_camera.py 2>&1 | tail -3 )

echo "==> bootstrap complete"
